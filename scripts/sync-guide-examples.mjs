import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const examples = {
  appDockerfile: "Dockerfile",
  postgresBackupScript: "examples/postgres/backup.sh",
  postgresRestoreScript: "examples/postgres/restore-check.sh",
  postgresCompose: "examples/postgres/compose.yml",
  appCompose: "examples/app.compose.yml",
  laboratoryWorkflow: "examples/build-and-deploy.yml",
};
const lines = ["// Generated by npm run examples:sync. Edit the files in examples/ instead."];
for (const [name, path] of Object.entries(examples)) {
  lines.push(`export const ${name} = ${JSON.stringify(await readFile(new URL(path, root), "utf8"))};`);
}
const generated = `${lines.join("\n\n")}\n`;
const target = new URL("src/content/operation-examples.ts", root);
if (process.argv.includes("--check")) {
  const existing = await readFile(target, "utf8").catch(() => "");
  if (existing !== generated) {
    throw new Error(`Exemplos desatualizados: executa npm run examples:sync (${fileURLToPath(target)})`);
  }
  console.log("Exemplos do guia sincronizados");
} else {
  await writeFile(target, generated);
}
